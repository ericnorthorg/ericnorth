    <li>Кожна сторінка має свою <b>адресу</b>: <code>/p/адреса</code>, наприклад <code>/p/about</code>. Мовні версії: <code>/en/p/about</code>, <code>/ru/p/about</code>, <code>/uk/p/about</code>.</li>
