<section id="pg-home">
  <h3>15. Головна сторінка з блоків</h3>
  <p>Головну сайту можна показувати у двох варіантах:</p>
  <ul>
    <li><b>«Классическую главную»</b> — як раніше: шапка й промо-блоки редагуються в розділі «Главная» адмінки, картки й форма — у «Настройках».</li>
    <li><b>«Главную из блоков»</b> — головна збирається в конструкторі, як будь-яка сторінка, з усіма 17 видами блоків.</li>
  </ul>
  <h4>Як перейти на головну з блоків</h4>
  <ol>
    <li>«Страницы» → панель «Главная страница» → <b>«Создать главную из блоков (копия текущей)»</b>. Створюється копія класичної головної: шапка, картки (з «наїздом» на шапку), «Продолжить чтение», усі видимі промо-блоки як «Картинка и текст», форма «Написать автору». <b>Сайт при цьому не змінюється.</b></li>
    <li>З'явиться повідомлення «Главная из блоков создана. Сайт пока не изменился.» Відредагуйте її (кнопка «Редактировать») і <b>опублікуйте</b>.</li>
    <li>У панелі «Что показывать на сайте» оберіть <b>«Главную из блоков»</b> і підтвердьте («Показать на сайте главную из блоков? …»). Перемикання діє одразу: «На сайте теперь главная из блоков».</li>
  </ol>
  <ul>
    <li>Вибрати головну з блоків можна лише після її першої публікації — інакше адмінка підкаже «Сначала откройте главную из блоков и опубликуйте её».</li>
    <li>Повернути класичну можна будь-коли тим самим перемикачем. Обидві версії зберігаються незалежно.</li>
    <li>Кнопка «На сайте» в редакторі головної відкриває головну сайту. У меню її окремо не додають (у налаштуваннях головної немає кнопки меню).</li>
    <li>Зміни в головній з блоків, як і в будь-якій сторінці, потрапляють на сайт лише після «Опубликовать». А зміни в класичній головній (розділи «Главная» й «Настройки» адмінки) на головну з блоків <b>не впливають</b> — це окремі копії.</li>
  </ul>
</section>

