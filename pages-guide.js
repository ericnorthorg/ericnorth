// Показ посібника в адмінці (вызывается из SECTIONS.guide в admin.html)
function renderPagesGuide() {
    const main = document.getElementById('main');
    main.innerHTML = '';
    // Підсвічуємо в меню «Страницы» — посібник належить до них
    document.querySelectorAll('#nav .nav-item').forEach(b => b.classList.toggle('active', b.dataset.s === 'pages'));
    main.append(
        el('div', { class: 'page-head' }, [
            el('div', {}, [
                el('button', { class: 'link-btn', style: 'margin:0 0 6px', type: 'button', onclick: () => go('pages'), html: '<i class="fa-solid fa-arrow-left"></i> К страницам' }),
                el('h2', { text: 'Посібник: конструктор сторінок' }),
                el('div', { class: 'sub', text: `Як створювати, редагувати й публікувати сторінки сайту. Оновлено ${PAGES_GUIDE_UPDATED}.` })])]),
        el('div', { class: 'form pg-guide', html: PAGES_GUIDE_HTML }));
    // Внутрішні переходи за змістом (не через #, бо # у адмінці — це розділи)
    main.querySelectorAll('.pg-guide a[data-pg]').forEach(a => {
        a.href = 'javascript:void 0';
        a.addEventListener('click', e => { e.preventDefault(); const t = document.getElementById(a.dataset.pg); if (t) t.scrollIntoView({ behavior: 'smooth', block: 'start' }); });
    });
    window.scrollTo(0, 0);
}
